STRIP_PAREN = re.compile(r'\([^)]*\)')
STRIP_BRACKET = re.compile(r'\[[^]]*\]')

def clean(s):
    s = s.strip()
    s = STRIP_BRACKET.sub(' ', s)
    s = STRIP_PAREN.sub(' ', s)
    s = s.split(';')[0]
    s = re.sub(r'\s+', ' ', s).strip()
    return s

# Bo nhan xưng 's, viet tat phu dinh, giu nghia loi.
NORMALIZE = [
    (re.compile(r"cow's", re.I), 'cow'),
    (re.compile(r"person's", re.I), 'person'),
    (re.compile(r"father's", re.I), 'father'),
    (re.compile(r"don't", re.I), 'do not'),
    (re.compile(r"there's", re.I), 'there is'),
    (re.compile(r"'s\b"), ''),
    (re.compile(r"'"), ''),
]

def normalize(s):
    for pat, rep in NORMALIZE:
        s = pat.sub(rep, s)
    return s

