MARKS={'ā':('a',1),'á':('a',2),'ǎ':('a',3),'à':('a',4),'ē':('e',1),'é':('e',2),'ě':('e',3),'è':('e',4),'ī':('i',1),'í':('i',2),'ǐ':('i',3),'ì':('i',4),'ō':('o',1),'ó':('o',2),'ǒ':('o',3),'ò':('o',4),'ū':('u',1),'ú':('u',2),'ǔ':('u',3),'ù':('u',4),'ǖ':('ü',1),'ǘ':('ü',2),'ǚ':('ü',3),'ǜ':('ü',4),'ü':('ü',5),'ê':('e',5)}
def to_num(s):
    out=[]
    for syl in s.split():
        tone=5; base=''
        for ch in syl:
            if ch in MARKS:
                b,t=MARKS[ch]; base+=b
                if t!=5: tone=t
            else: base+=ch
        out.append(base.lower()+str(tone))
    return ' '.join(out)

def sense(e):
    tr = [t for t in e['translations'] if not t.startswith('CL:')]
    if not tr:
        tr = list(e['translations'])
    s = tr[0]
    # clem109 cat nghia tai ';' lam vo ngoac: noi lai manh tiep theo.
    if s.count('(') != s.count(')') and len(tr) > 1:
        s = s + ', ' + tr[1]
    return s

