def main():
    clem_by, drk = {}, {}
    for n in (2, 3, 4):
        cl = json.loads((RAW / "clem109" / ("hsk-vocab-json/hsk-level-%d.json" % n)).read_text(encoding="utf-8"))
        d = collections.defaultdict(list)
        for e in cl:
            d[e["hanzi"]].append(to_num(e["pinyin"]))
        clem_by[n] = d
        drk[n] = {e["simplified"]: e for e in
                  json.loads((RAW / ("drk-old-%d.json" % n)).read_text(encoding="utf-8"))}
    seen, rows = set(), []
    for n in (2, 3, 4):
        cl = json.loads((RAW / "clem109" / ("hsk-vocab-json/hsk-level-%d.json" % n)).read_text(encoding="utf-8"))
        for e in cl:
            if e["hanzi"] in seen:
                continue
            seen.add(e["hanzi"])
            s = sense(e)
            py = pick_pinyin(e["hanzi"], n, drk[n][e["hanzi"]], clem_by[n][e["hanzi"]])
            g = OVERRIDES.get(e["hanzi"])
            if g is None:
                g, un, _ = translate(s)
                assert not un and g, (n, e["hanzi"], s, un)
            tone = " ".join(ch for ch in py if ch.isdigit())
            assert len(py.split()) == len(tone.split()), (n, e["hanzi"], py)
            assert tone and all(c in "12345" for c in tone.split()), (n, e["hanzi"], tone)
            rows.append((n, e["hanzi"], py, tone, g))
    counts = collections.Counter(n for n, _, _, _, _ in rows)
    assert dict(counts) == {2: 147, 3: 298, 4: 598}, dict(counts)

    def gs(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    levels = collections.defaultdict(list)
    for (n, hz, py, tone, g) in rows:
        levels[n].append((hz, py, g, tone))
    dest = REPO / "api" / "hsk_seed_l234.go"
    with io.open(dest, "w", encoding="utf-8") as f:
        f.write("package main\n\n")
        f.write("// T8.1 — seed HSK 2.0 L2-L4 (1043 tu unique theo hanzi+level).\n")
        f.write("// Sinh boi scripts/seed_hsk.py — khong sua tay (sua script roi chay lai).\n")
        f.write("// Nguon: drkameleon/complete-hsk-vocabulary (MIT, Copyright (c) 2026 Yanis Zafir\u00f3pulos);\n")
        f.write("// doi chieu clem109/hsk-vocabulary (MIT, Copyright (c) 2018 Clement Venard);\n")
        f.write("// pinyin tham khao CC-CEDICT (CC BY-SA 4.0), nghia Viet nhom tu soan.\n\n")
        for n in (2, 3, 4):
            f.write("// hsk%dSeed: %d tu HSK%d.\n" % (n, len(levels[n]), n))
            f.write("var hsk%dSeed = []HskEntry{\n" % n)
            for (hz, py, g, tone) in levels[n]:
                f.write("\t{%s, %s, %s, \"HSK%d\", %s},\n" % (gs(hz), gs(py), gs(g), n, gs(tone)))
            f.write("}\n\n")
        f.write("// hskSeedByLevel tra seed theo level (HSK1 nam trong chinese_hsk.go — giu 36 tu).\n")
        f.write("func hskSeedByLevel(level string) []HskEntry {\n")
        f.write('\tswitch level {\n\tcase "HSK2":\n\t\treturn hsk2Seed\n')
        f.write('\tcase "HSK3":\n\t\treturn hsk3Seed\n\tcase "HSK4":\n\t\treturn hsk4Seed\n')
        f.write("\tdefault:\n\t\treturn nil\n\t}\n}\n")
    print("SeedHSK OK: %d entries -> %s" % (len(rows), dest))


