def pick_pinyin(hz, level, dr_entry, clem_nums):
    if hz in PINYIN_FIX: return PINYIN_FIX[hz]
    if hz in POLY: return POLY[hz]
    dforms=[' '.join(f['transcriptions']['numeric'].lower().split()) for f in dr_entry['forms']]
    if dforms[0] in clem_nums: return dforms[0]
    for d in dforms[1:]:
        if d in clem_nums: return d
    return dforms[0]

